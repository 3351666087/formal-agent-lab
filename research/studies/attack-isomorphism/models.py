def _abstract(src: LTS) -> LTS:
    """A semantics-free relabelling: states s1..sn, actions a1..am (control arm for
    naming). Order follows the declared tuple order, so it is deterministic."""
    sm = {s: f"s{i+1}" for i, s in enumerate(src.states)}
    am = {a: f"a{i+1}" for i, a in enumerate(src.actions)}
    return relabel(src, sm, am, src.name + "_abstract",
                   "abstract control vocabulary (no domain)", "abstract arm of " + src.name)


