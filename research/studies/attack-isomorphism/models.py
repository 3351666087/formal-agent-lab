"""Attack-model ⇄ real-world isomorphism study (v3).

v3 changes:
  * Models B and C are enlarged to faithfully-sized state machines: TLS is a composite
    handshake with an RSA branch and a (EC)DHE branch (ServerKeyExchange); WPA2 includes
    the group-key handshake on top of the 4-way handshake (KRACK attacks both).
  * Every bad state is now reachable by TWO independent mechanisms, each tagged with a
    named control/defence, so the "minimal defence set" is non-trivial (size 2).
  * The real-world twins are reworked to natural business processes whose own standard
    lifecycle matches the protocol's — a tenancy/lease lifecycle, a loan-underwriting
    pipeline, a credential issuance-and-rotation system — so that the two solving tasks
    ("minimal controls to prevent the bad outcome", "shortest sequence to the bad outcome")
    are genuine, legitimate business questions.
  * Twins are still generated by a programmatic relabelling, so each is EXACTLY isomorphic
    to its attack model (verified by z3), including the defence tags.

Sources (state machines reproduced faithfully to the papers / standards they model):
  A — TCP connection, RFC 793. Pacheco et al. (KORG), TCP phi1 "no half-open connections".
      Two injection mechanisms: spoofed RST, and in-window SYN injection (RFC 5961 context).
  B — TLS 1.2 composite handshake. de Ruiter & Poll (USENIX 2015); Beurdouche et al. SMACK
      / FREAK (S&P 2015). Two flaws: FREAK export-grade downgrade, and skip-auth early data.
  C — WPA2 4-way + group-key handshakes (802.11; KRACK, Vanhoef & Piessens CCS 2017). Two
      reinstallation mechanisms: replayed message 3 (PTK), replayed group message 1 (GTK).
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class LTS:
    name: str
    states: tuple[str, ...]
    actions: tuple[str, ...]
    transitions: tuple[tuple[str, str, str], ...]
    initial: str
    bad: tuple[str, ...]
    # the normal "success" state that must stay reachable — this is what makes the minimal-
    # control task well-defined (you may not prevent the bad outcome by breaking normal use).
    success: tuple[str, ...] = ()
    # action -> control/defence that disables every transition using that action.
    # Only the malicious actions carry a defence; benign actions are absent.
    defense: dict[str, str] = field(default_factory=dict)
    domain: str = ""
    source: str = ""

    def __post_init__(self) -> None:
        S, A = set(self.states), set(self.actions)
        assert self.initial in S, f"{self.name}: initial not a state"
        assert set(self.bad) <= S, f"{self.name}: bad not a subset of states"
        for s, a, d in self.transitions:
            assert s in S and d in S and a in A, f"{self.name}: bad edge {(s, a, d)}"
        assert set(self.defense) <= A, f"{self.name}: defence on unknown action"


@dataclass(frozen=True)
class Twin:
    key: str
    attack: LTS
    real: LTS
    state_map: dict[str, str]
    action_map: dict[str, str]
    rationale: str = ""


def relabel(src: LTS, sm: dict[str, str], am: dict[str, str],
            name: str, domain: str, source: str) -> LTS:
    assert sorted(sm) == sorted(src.states) and len(set(sm.values())) == len(sm)
    assert sorted(am) == sorted(src.actions) and len(set(am.values())) == len(am)
    return LTS(
        name=name,
        states=tuple(sm[s] for s in src.states),
        actions=tuple(am[a] for a in src.actions),
        transitions=tuple((sm[s], am[a], sm[d]) for s, a, d in src.transitions),
        initial=sm[src.initial],
        bad=tuple(sm[b] for b in src.bad),
        success=tuple(sm[s] for s in src.success),
        defense={am[a]: _dmap.get(dname, dname) for a, dname in src.defense.items()},
        domain=domain, source=source,
    )


